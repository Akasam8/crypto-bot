"""Builds the claude_project/ folder: files to upload into a Claude Project so Claude has full context."""
from __future__ import annotations

import shutil

import pandas as pd

from .config import PROJECT_DIR, REPORTS_DIR, STATE_DIR

INSTRUCTIONS = """# Instructions for Claude: crypto-bot analyst

You're the analyst for my Coinbase crypto bot. The bot runs on GitHub Actions, scans 25 coins every hour,
and only trades setups that survived a backtest on 3 years of hourly data. The files in this project are
regenerated by the bot: playbook.md (how the market behaves + the live strategy cards), backtest_report.md
(the full verdict), and journal_summary.md (every signal and trade so far, paper or live).

How to help me:
1. Only quote numbers that are in these files. Never invent a probability, win rate or price target. If I ask
   "what's the chance X goes up", answer with the setup's historical win rate and sample size from the files,
   or say there's no tested setup for it.
2. When I ask about a signal, check it against its strategy card: regime, typical stop and target, how that
   setup has done in the journal so far versus the backtest.
3. You can use web search for news on a coin (hacks, delistings, exchange problems, big token unlocks,
   lawsuits, macro events like a Fed decision) and recommend skipping a trade because of it. You can't
   create new trades or change the numbers.
4. Explain wins and losses in plain English. Losing trades are normal; judge setups on 30+ trades, not one.
5. Push back hard if I want to break the risk rules: no leverage, no futures or perpetuals, no raising size
   before the journal proves the setup, no turning the bot back on after a halt without reviewing why.
6. Every week, compare journal results with the backtest. If a setup is doing much worse after 30+ trades,
   say so and suggest pausing it.

Keep answers short and direct. I'm in London, so use UK time.
"""


def journal_summary(cfg: dict) -> str:
    p = STATE_DIR / "trades.csv"
    L = ["# Journal summary\n"]
    if not p.exists():
        L.append("No trades yet.\n")
        return "\n".join(L)
    df = pd.read_csv(p)
    closed = df[df["status"] == "closed"]
    open_ = df[df["status"] == "open"]
    pot = cfg["risk"]["pot_start_gbp"] + closed["pnl_gbp"].sum()
    L.append(f"Mode: {cfg['mode']}. Closed trades: {len(closed)}. Open: {len(open_)}. Pot after closed trades: £{pot:.2f} (started £{cfg['risk']['pot_start_gbp']:.0f}).\n")
    if len(closed):
        L.append(f"Win rate {(closed['pnl_gbp'] > 0).mean() * 100:.0f}%, total £{closed['pnl_gbp'].sum():+.2f}, average {closed['pnl_pct'].mean():+.2f}% per trade after fees.\n")
        L.append("| Setup | Trades | Win rate | Avg % | Total £ |")
        L.append("|---|---|---|---|---|")
        for s, g in closed.groupby("setup"):
            L.append(f"| {s} | {len(g)} | {(g['pnl_gbp'] > 0).mean() * 100:.0f}% | {g['pnl_pct'].mean():+.2f}% | £{g['pnl_gbp'].sum():+.2f} |")
        L.append("")
    cols = ["id", "mode", "coin", "setup", "entry_time", "entry_price", "size_gbp", "exit_time", "exit_reason", "pnl_gbp", "pnl_pct", "status"]
    L.append("## Last 40 trades\n")
    L.append(df.tail(40)[[c for c in cols if c in df.columns]].to_markdown(index=False) if hasattr(df, "to_markdown") else df.tail(40).to_csv(index=False))
    return "\n".join(L)


def write_project_pack(cfg: dict, with_journal: bool = False):
    PROJECT_DIR.mkdir(parents=True, exist_ok=True)
    (PROJECT_DIR / "project_instructions.md").write_text(INSTRUCTIONS)
    for name in ("playbook.md", "backtest_report.md", "strategy_cards.md"):
        src = REPORTS_DIR / name
        if src.exists():
            shutil.copyfile(src, PROJECT_DIR / name)
    if with_journal:
        write_journal_summary(cfg)


def write_journal_summary(cfg: dict):
    PROJECT_DIR.mkdir(parents=True, exist_ok=True)
    try:
        text = journal_summary(cfg)
    except Exception as e:  # noqa: BLE001
        text = f"# Journal summary\n\nCouldn't build summary: {e}\n"
    (PROJECT_DIR / "journal_summary.md").write_text(text)
